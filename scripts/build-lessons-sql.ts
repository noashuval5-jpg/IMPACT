/**
 * npm run build:lessons — turns supabase/content/lessons.{he,ar}.txt into
 * supabase/lessons.sql, which is pasted once into the Supabase SQL Editor.
 * Flyers are served by the app itself from public/flyers/{he,ar}/week-NN.png.
 */
import { readFileSync, writeFileSync } from "node:fs";

type Lesson = { week: number; title: string; message: string; body: string };

function parse(path: string): Map<number, Lesson> {
  const text = readFileSync(path, "utf8");
  const lessons = new Map<number, Lesson>();
  for (const chunk of text.split(/^=== /m).slice(1)) {
    const [header = "", ...rest] = chunk.split("\n");
    const m = /^(\d+) \| (.+)$/.exec(header.trim());
    if (!m) throw new Error(`Bad header in ${path}: ${header}`);
    const joined = rest.join("\n");
    const msg = /^MSG: (.+)$/m.exec(joined)?.[1]?.trim();
    const bodyIndex = joined.indexOf("BODY:\n");
    if (!msg || bodyIndex < 0) throw new Error(`Missing MSG/BODY in lesson ${m[1]}`);
    const week = Number(m[1]);
    lessons.set(week, {
      week,
      title: m[2]!.trim(),
      message: msg,
      body: joined.slice(bodyIndex + "BODY:\n".length).trim(),
    });
  }
  return lessons;
}

const he = parse("supabase/content/lessons.he.txt");
const ar = parse("supabase/content/lessons.ar.txt");

function briefingHe(l: Lesson) {
  return `המסר: ${l.message}\n\n${l.body}`;
}
function briefingAr(l: Lesson) {
  return `الرسالة: ${l.message}\n\n${l.body}`;
}
function parentsHe(l: Lesson) {
  return [
    "הורים יקרים,",
    `היום בסוף האימון דיברנו עם הילדים על ${l.title}.`,
    `המסר שלנו: ${l.message}`,
    "מצרפים פלייר עם טיפים להורים. כדאי לדבר על זה גם בבית.",
    "עצור – הסתכל – חשוב – ואז זוז.",
  ].join("\n");
}
function parentsAr(l: Lesson) {
  return [
    "أهلنا الأعزاء،",
    `اليوم في نهاية التدريب تحدثنا مع الأولاد عن ${l.title}.`,
    `رسالتنا: ${l.message}`,
    "نرفق منشوراً مع نصائح للأهل. من المفيد أن تتحدثوا عن ذلك في البيت أيضاً.",
    "قِف – انظر – فكّر – ثم تحرّك.",
  ].join("\n");
}

/** Dollar-quoted SQL string, so quotes in the text need no escaping. */
function q(value: string): string {
  if (value.includes("$c$")) throw new Error("Text contains the SQL quote marker");
  return `$c$${value}$c$`;
}

const rows: string[] = [];
for (let w = 1; w <= 10; w++) {
  const h = he.get(w);
  const a = ar.get(w);
  if (!h || !a) throw new Error(`Lesson ${w} missing in one of the languages`);
  const nn = String(w).padStart(2, "0");
  rows.push(
    `(${w}, ${q(h.title)}, ${q(a.title)}, ${q(briefingHe(h))}, ${q(briefingAr(a))}, ${q(
      parentsHe(h),
    )}, ${q(parentsAr(a))}, '/flyers/he/week-${nn}.png', '/flyers/ar/week-${nn}.png', false)`,
  );
}

const sql = `-- =====================================================================
-- שריקת סיום — תוכן 10 השבועות (עברית + ערבית + פליירים)
-- Paste into Supabase → SQL Editor → New query → Run.
-- Running it again overwrites weeks 1-10 with this content.
-- Generated by: npm run build:lessons
-- =====================================================================
insert into public.lessons
  (week_number, title_he, title_ar, briefing_he, briefing_ar,
   message_he, message_ar, flyer_he_url, flyer_ar_url, is_demo)
values
${rows.join(",\n")}
on conflict (week_number) do update set
  title_he = excluded.title_he,
  title_ar = excluded.title_ar,
  briefing_he = excluded.briefing_he,
  briefing_ar = excluded.briefing_ar,
  message_he = excluded.message_he,
  message_ar = excluded.message_ar,
  flyer_he_url = excluded.flyer_he_url,
  flyer_ar_url = excluded.flyer_ar_url,
  is_demo = false,
  updated_at = now();
`;

writeFileSync("supabase/lessons.sql", sql);
console.log(`Wrote supabase/lessons.sql (${rows.length} lessons, ${sql.length} chars)`);
